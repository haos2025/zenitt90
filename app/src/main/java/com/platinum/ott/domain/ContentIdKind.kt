package com.platinum.ott.domain

/**
 * ФИКС (аудит): один и тот же класс бага уже чинился по отдельности —
 * GetPlayableUrlUseCase.kt (диспетчеризация по префиксу), HomeViewModel.
 * resolvePosterIfNeeded() (см. её же комментарий: "TMDB-поиск по названиям
 * плейлиста часто это имена IPTV-каналов, не фильмов — случайные неверные
 * совпадения"). Аудит нашёл ещё два места, где этой же защиты не было —
 * DetailViewModel.load() и SeriesTrackerUseCase.updateSchedule() — из-за
 * чего детальная карточка и уведомления о новых сериях для собственных
 * IPTV-каналов/фильмов могли получить постер/расписание совершенно
 * другого тайтла, случайно попавшего под текстовый поиск TMDB, и это
 * закэшировалось бы на 24 часа. Единая точка проверки, чтобы больше не
 * чинить один и тот же баг в пятый раз в новом месте.
 */
object ContentIdKind {
    private val ZENITH_BACKEND_PREFIXES = setOf("yt", "ia")

    /**
     * true только для контента, который пришёл с zenith-backend — там id
     * содержит настоящий внешний идентификатор (TMDB-каталог курирует сам
     * бэкенд), и текстовый поиск по названию для подбора метаданных
     * оправдан. Для собственных источников пользователя (m3u_/xt_/ch_ —
     * всё, что НЕ yt_/ia_) название — это то, что ввёл провайдер плейлиста
     * (часто название канала, обрезанное/грязное название файла и т.п.),
     * и слепой TMDB-поиск по нему давал бы случайные неверные совпадения.
     */
    fun isZenithBackendContent(id: String): Boolean =
        ZENITH_BACKEND_PREFIXES.any { id.startsWith("${it}_") || id.contains("_${it}_") }
}
