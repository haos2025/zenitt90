package com.platinum.ott.data.local.entity

import androidx.room.Entity
import androidx.room.PrimaryKey

/**
 * Канонический канал — то, что видит пользователь в списке "Каналы".
 * Отдельно от ChannelStreamEntity (см. рядом) специально: один и тот же
 * канал ("Первый канал") может отдаваться несколькими источниками
 * (M3U-плейлист А, Xtream-панель Б) под разными URL и с разным текстом
 * названия — Channel один, ChannelStreamEntity под него несколько.
 *
 * ДО этой сущности источник живого эфира представлялся как обычная
 * запись PlaylistMovieEntity (одна строка = один (источник, канал), без
 * разделения понятий) — из-за этого избранное дублировалось при
 * добавлении второго источника с теми же каналами, и не было способа
 * переключиться на другой источник при отказе одного, не потеряв
 * избранное/историю, привязанные к id конкретной старой записи.
 *
 * id генерируется один раз при создании канала (UUID) и НЕ пересчитывается
 * при последующих refresh() источников — именно он должен быть стабильной
 * точкой, на которую ссылаются избранное/история, независимо от того,
 * сколько источников сейчас отдают этот канал и что там менялось у них
 * внутри (ChannelStream можно пересоздавать при каждом refresh, Channel —
 * нет).
 */
@Entity(tableName = "channels")
data class ChannelEntity(
    @PrimaryKey val id: String,
    // Редактируемое пользователем отображаемое имя — при автосоздании
    // канала (совпадение по tvgId) берётся название из первого источника,
    // дальше пользователь может переименовать независимо от источников.
    val canonicalName: String,
    // Ключ автосопоставления между источниками — см. PROMPT_IPTV_FOUNDATION.md,
    // раздел "Сопоставление каналов между источниками". Может отсутствовать
    // (не все плейлисты его проставляют) — тогда канал не автосопоставляется
    // ни с чем, только вручную через UI слияния (отдельная подзадача).
    val tvgId: String? = null,
    val logo: String? = null,
    val category: String? = null,
    // Явное поле для различения одноимённых каналов разных регионов
    // ("Первый канал (Москва)" vs "Первый канал (Владивосток)") — намеренно
    // не подразумевается через парсинг названия, чтобы не гадать.
    // Заполняется пользователем вручную через UI (не автоматически).
    val regionHint: String? = null,
    // Каналов у типичного провайдера могут быть тысячи — пользователь
    // явно выбирает нужные, а не видит все сразу как готовый список.
    val isSubscribed: Boolean = false,
    // PROMPT_EPG.md, подзадача 6 (заппинг по номерам) — то же поле, что и
    // порядок в списке "Каналы" (сортировка по нему уже была — ChannelDao.getAll()/
    // getSubscribed() ORDER BY sortOrder), теперь ЕЩЁ и номер, который
    // набирают на пульте: разводить "порядок в списке" и "номер канала" на
    // два разных поля означало бы либо держать их искусственно
    // синхронными, либо объяснять пользователю, почему они расходятся —
    // для этого приложения это одно и то же понятие. Источник значения —
    // явный tvg-chno (M3U) / num (Xtream), если есть (см.
    // ChannelMatchingRepository.resolveChannelId()); если нет — авто-номер
    // по возрастанию при первом создании канала, стабильный дальше (тот же
    // принцип, что и у id — не пересчитывается на каждый refresh).
    val sortOrder: Int = 0
)
